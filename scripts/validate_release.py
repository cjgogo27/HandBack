"""Fail closed on broken local links, accidental private paths, secrets or invalid evidence."""
from pathlib import Path
import ast, hashlib, html.parser, json, re, sys
from urllib.parse import unquote
from handback.analysis import verify

ROOT=Path(__file__).resolve().parents[1]
EXCLUDED={'.git','__pycache__','build','dist'}

def files():
    return [p for p in ROOT.rglob('*') if p.is_file() and not any(x in EXCLUDED or x.endswith('.egg-info') for x in p.relative_to(ROOT).parts)]

def check():
    checked=0
    for p in files():
        if p.suffix.lower() in ('.png','.zip','.pdf','.pyc','.webp','.mp4'):continue
        text=p.read_text(encoding='utf8')
        assert not re.search(r'(?:sk-|gh[pousr]_|github_pat_)[A-Za-z0-9_\-]{20,}',text),f'Possible credential in {p.name}'
        assert not re.search(r'-----BEGIN (?:RSA |OPENSSH |EC )?PRIVATE KEY-----',text),f'Private key in {p.name}'
        # Public artifact IDs retain only study names, never storage accounts or machine paths.
        if p.resolve()!=Path(__file__).resolve():
            assert not re.search(r'/data(?:7t-root)?/alice/|/home/eir/|C:[/\\]Users[/\\]',text),f'Private path in {p.name}'
        if p.suffix=='.py':ast.parse(text)
        if p.suffix=='.md':
            for target in re.findall(r'(?<!!)\[[^\]]+\]\(([^)]+)\)',text):
                if re.match(r'^(https?://|mailto:|#)',target):continue
                target=unquote(target.split('#',1)[0])
                assert (p.parent/target).exists(),f'Broken relative link {p.relative_to(ROOT)} -> {target}'
        checked+=1
    s=verify(ROOT)
    assert s['logical_units']==84 and s['physical_attempts_including_original_partials']==87
    report=(ROOT/'docs/report.md').read_text(encoding='utf8')
    assert '6/12' in report and 'not externally preregistered' in report
    assert (ROOT/'docs/index.html').exists() and (ROOT/'docs/assets/outcomes.svg').exists()
    media=json.loads((ROOT/'data/media_manifest.json').read_text(encoding='utf8'))
    assert len(media['gallery'])==84 and len(media['replays'])==3 and len(media['derived_peaks'])==2
    for r in media['gallery']+media['replays']+media['derived_peaks']:
        p=ROOT/'docs/assets/media'/r['file']
        assert p.is_file() and hashlib.sha256(p.read_bytes()).hexdigest()==r['sha256'], f'Media mismatch {r["file"]}'
    assert media['paired_scene_4002_native_observation_hashes_identical']
    assert not re.search(r'(?:AI[- ]generated|generated by AI|experiments? (?:were )?(?:run|conducted) by AI)',report,re.I)
    return dict(state='passed',text_files_checked=checked,evidence_rows=84,
                scope='Public-package consistency, privacy pattern checks and local links; not external replication')

if __name__=='__main__':print(json.dumps(check(),indent=2))
